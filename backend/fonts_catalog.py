"""
The curated font library.

`manifest.json` is generated by `backend/scripts/fetch_typefaces.py`, which
downloads each family's static TTFs and records which faces it actually got.
This module reads that manifest and cross-checks it against the files on disk,
so the catalog cannot advertise a bold the directory does not contain — the
failure mode that made the Style toggle a silent no-op in the PDF.

The manifest is the source of truth for *availability*; a family whose regular
face is missing is dropped rather than offered and then failing at render time.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache

from .paths import TYPEFACES_DIR, resolve

MANIFEST_PATH = TYPEFACES_DIR / "manifest.json"


@dataclass(frozen=True)
class Font:
    id: str
    label: str
    category: str
    path: str            # repo-relative, points at the regular face
    has_bold: bool
    has_italic: bool
    google_family: str
    # SPDX id of the license file sitting beside the faces. Recorded because the
    # binaries are redistributed in this repo, so which license applies to which
    # family has to be recoverable without downloading anything.
    license: str = "unknown"

    @property
    def styles(self) -> list[str]:
        """The Style toggle's options, limited to faces that exist on disk."""
        out = ["normal"]
        if self.has_bold:
            out.append("bold")
        if self.has_italic:
            out.append("italic")
        return out


@lru_cache(maxsize=1)
def _load() -> tuple[Font, ...]:
    if not MANIFEST_PATH.exists():
        return ()

    try:
        raw = json.loads(MANIFEST_PATH.read_text())
    except (OSError, json.JSONDecodeError):
        return ()

    fonts = []
    for entry in raw:
        regular = resolve(entry["path"])
        if not regular.exists():
            # Manifest and disk disagree. Trust the disk: offering a font that
            # isn't there turns into a failed render, not a missing option.
            continue

        directory = regular.parent
        stem = regular.stem
        fonts.append(Font(
            id=entry["id"],
            label=entry["label"],
            category=entry.get("category", "Other"),
            path=entry["path"],
            has_bold=bool(entry.get("has_bold")) and (directory / f"{stem}-Bold.ttf").exists(),
            has_italic=bool(entry.get("has_italic")) and (directory / f"{stem}-Italic.ttf").exists(),
            google_family=entry.get("google_family", entry["label"]),
            license=entry.get("license", "unknown"),
        ))
    return tuple(fonts)


def all_fonts() -> list[Font]:
    return list(_load())


def get(font_id: str) -> Font | None:
    return next((f for f in _load() if f.id == font_id), None)


def by_path(path: str) -> Font | None:
    """Reverse lookup, for rebuilding the picker's selection from a saved event."""
    return next((f for f in _load() if f.path == path), None)
